#!/usr/bin/env node
/**
 * Dependency licence audit.
 *
 * - Every package that ships in the built site (production dependency tree)
 *   must use a licence on the ALLOWED list; anything else fails the audit.
 * - Development-only tools are listed too; copyleft there is reported but
 *   does not fail, since none of that code is distributed.
 * - Writes THIRD_PARTY_LICENSES.md with the shipped packages and their notices.
 *
 * "Shipped" means the production dependency tree of the web app (apps/web),
 * resolved across the whole workspace. Internal @ihatecircuits/* workspace
 * packages are our own MIT-licensed code, so they are counted separately and
 * not audited as third-party.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', 'OFL-1.1', '0BSD', 'CC0-1.0', 'BlueOak-1.0.0', 'Unlicense']);
const COPYLEFT = /\b(A?GPL|LGPL|SSPL|EUPL|MPL|CDDL|EPL)\b/i;

function licenseOf(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(' OR ');
  if (l && typeof l === 'object') return l.type ?? 'UNKNOWN';
  return 'UNKNOWN';
}

/** An SPDX expression passes if every AND-term has at least one allowed OR-option. */
function allowed(expr) {
  const clean = expr.replace(/[()]/g, ' ');
  return clean.split(/\s+AND\s+/).every((term) => term.split(/\s+OR\s+/).some((opt) => ALLOWED.has(opt.trim())));
}

const SHIPPED_WORKSPACE = '@ihatecircuits/web';
const INTERNAL_SCOPE = '@ihatecircuits/';

const prodPaths = new Set(
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable', '-w', SHIPPED_WORKSPACE], { cwd: ROOT, encoding: 'utf8' })
    .split('\n')
    .filter((p) => p.includes('node_modules')),
);

const all = [];
const internal = [];
function walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const p = join(dir, name);
    if (name.startsWith('@')) {
      walk(p);
      continue;
    }
    const pj = join(p, 'package.json');
    if (existsSync(pj)) {
      const pkg = JSON.parse(readFileSync(pj, 'utf8'));
      if (pkg.name?.startsWith(INTERNAL_SCOPE)) internal.push(pkg.name);
      else if (pkg.name) all.push({ path: p, name: pkg.name, version: pkg.version, license: licenseOf(pkg), prod: prodPaths.has(p), homepage: pkg.homepage ?? pkg.repository?.url ?? pkg.repository ?? '' });
    }
    walk(join(p, 'node_modules'));
  }
}
walk(join(ROOT, 'node_modules'));
// npm nests a package inside a workspace when two workspaces need different versions.
for (const group of ['packages', 'apps']) {
  if (!existsSync(join(ROOT, group))) continue;
  for (const ws of readdirSync(join(ROOT, group))) walk(join(ROOT, group, ws, 'node_modules'));
}

// Type declarations are erased at build time, so they never reach the site.
const TYPE_ONLY = (name) => name.startsWith('@types/') || name === 'csstype';
const prod = all.filter((p) => p.prod && !TYPE_ONLY(p.name)).sort((a, b) => a.name.localeCompare(b.name));
const dev = all.filter((p) => !p.prod || TYPE_ONLY(p.name));
const failures = prod.filter((p) => !allowed(p.license));
const devFlags = dev.filter((p) => COPYLEFT.test(p.license) || p.license === 'UNKNOWN');

const counts = {};
for (const p of all) counts[p.license] = (counts[p.license] ?? 0) + 1;

console.log(`Scanned ${all.length} installed packages (${prod.length} shipped, ${dev.length} development-only).`);
if (internal.length) console.log(`Internal workspace packages (ours, MIT, not audited): ${internal.sort().join(', ')}.`);
console.log('Licences:', Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ×${n}`).join(', '));
for (const p of devFlags) console.log(`note: dev-only ${p.name}@${p.version} is ${p.license} (not shipped)`);

function noticeFor(p) {
  const file = readdirSync(p.path).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  return file ? readFileSync(join(p.path, file), 'utf8').trim() : `Licensed under ${p.license}.`;
}

const md = [
  '# Third-party licences',
  '',
  'Generated by `npm run licenses` (tools/license-audit.mjs). Do not edit by hand.',
  '',
  'These packages are bundled into the built site. Development tools (build, test) are not distributed and are audited separately by the same script.',
  '',
  '| Package | Version | Licence |',
  '| --- | --- | --- |',
  ...prod.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
  '',
  ...prod.flatMap((p) => [`## ${p.name}@${p.version}`, '', '```', noticeFor(p), '```', '']),
].join('\n');
writeFileSync(join(ROOT, 'THIRD_PARTY_LICENSES.md'), md);
console.log(`Wrote ${relative(process.cwd(), join(ROOT, 'THIRD_PARTY_LICENSES.md'))}.`);

if (failures.length) {
  console.error('\nShipped packages with licences outside the allowed list:');
  for (const p of failures) console.error(`  ${p.name}@${p.version}: ${p.license}`);
  process.exit(1);
}
console.log('All shipped packages use allowed licences.');
